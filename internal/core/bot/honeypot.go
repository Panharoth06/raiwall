package bot

import (
	"bytes"
	"fmt"
	"strings"
)

// DefaultTrapPrefix is the URL path prefix for dynamic honeypot traps.
const DefaultTrapPrefix = "/.raiwall/trap"

// DefaultTrapPath is the default honeypot link path.
const DefaultTrapPath = "/.raiwall/trap/crawler"

// SPAMarkers are token signatures that identify Single Page Application (SPA)
// or Server-Side Rendered (SSR) hydration frameworks.
var SPAMarkers = [][]byte{
	[]byte(`id="__next"`),
	[]byte(`id="app"`),
	[]byte(`id="root"`),
	[]byte(`id="__nuxt"`),
	[]byte(`data-reactroot`),
	[]byte(`__NEXT_DATA__`),
	[]byte(`__NUXT__`),
	[]byte(`data-server-rendered`),
	[]byte(`ng-version`),
	[]byte(`<app-root`),
	[]byte(`svelte-`),
}

// HoneypotInjector injects hidden crawler traps into static HTML responses
// while preserving 100% hydration safety for React/Vue/Next.js/Nuxt SPAs.
type HoneypotInjector struct {
	trapPath string
}

// NewHoneypotInjector constructs an initialized HoneypotInjector.
func NewHoneypotInjector(trapPath string) *HoneypotInjector {
	if trapPath == "" {
		trapPath = DefaultTrapPath
	}
	return &HoneypotInjector{
		trapPath: trapPath,
	}
}

// TrapPath returns the active honeypot target URL.
func (h *HoneypotInjector) TrapPath() string {
	return h.trapPath
}

// DetectSPA inspects HTML content to determine whether it is generated by
// an SPA or SSR framework where DOM mutation would trigger hydration mismatch errors.
// It executes with zero heap allocations.
func DetectSPA(html []byte) bool {
	if len(html) == 0 {
		return false
	}
	for _, marker := range SPAMarkers {
		if containsCaseInsensitive(html, marker) {
			return true
		}
	}
	return false
}

// Inject inspects the HTML content. If the page is a modern SPA, it is returned
// completely unmodified (injected=false). If the page is static HTML, a hidden honeypot
// anchor tag is inserted immediately before </body> (injected=true).
func (h *HoneypotInjector) Inject(html []byte) ([]byte, bool) {
	if len(html) == 0 {
		return html, false
	}

	// 1. SPA Hydration Safety Check: do not touch SPA/SSR responses
	if DetectSPA(html) {
		return html, false
	}

	// Check if already injected
	trapTagBytes := []byte(h.trapPath)
	if bytes.Contains(html, trapTagBytes) {
		return html, false
	}

	trapHoleHTML := fmt.Sprintf(`<a href="%s" style="display:none" rel="nofollow" aria-hidden="true" tabindex="-1"></a>`, h.trapPath)
	trapBytes := []byte(trapHoleHTML)

	// 2. Find closing </body> tag (case-insensitive, zero allocation)
	bodyCloseIdx := lastIndexCaseInsensitive(html, []byte("</body>"))
	if bodyCloseIdx != -1 {
		res := make([]byte, 0, len(html)+len(trapBytes))
		res = append(res, html[:bodyCloseIdx]...)
		res = append(res, trapBytes...)
		res = append(res, html[bodyCloseIdx:]...)
		return res, true
	}

	// 3. Fallback: find closing </html> tag
	htmlCloseIdx := lastIndexCaseInsensitive(html, []byte("</html>"))
	if htmlCloseIdx != -1 {
		res := make([]byte, 0, len(html)+len(trapBytes))
		res = append(res, html[:htmlCloseIdx]...)
		res = append(res, trapBytes...)
		res = append(res, html[htmlCloseIdx:]...)
		return res, true
	}

	// 4. Fallback: if document has <body> or <html> opening tag, append before EOF
	if containsCaseInsensitive(html, []byte("<body")) || containsCaseInsensitive(html, []byte("<html")) {
		res := make([]byte, 0, len(html)+len(trapBytes))
		res = append(res, html...)
		res = append(res, trapBytes...)
		return res, true
	}

	// Plain text or non-HTML: do not mutate
	return html, false
}

// containsCaseInsensitive searches for needle in haystack without any heap allocations.
func containsCaseInsensitive(haystack, needle []byte) bool {
	if len(needle) == 0 {
		return true
	}
	if len(haystack) < len(needle) {
		return false
	}
	limit := len(haystack) - len(needle)
	firstLower := needle[0]
	if firstLower >= 'A' && firstLower <= 'Z' {
		firstLower += 32
	}

	for i := 0; i <= limit; i++ {
		b := haystack[i]
		if b >= 'A' && b <= 'Z' {
			b += 32
		}
		if b == firstLower {
			match := true
			for j := 1; j < len(needle); j++ {
				hb := haystack[i+j]
				if hb >= 'A' && hb <= 'Z' {
					hb += 32
				}
				nb := needle[j]
				if nb >= 'A' && nb <= 'Z' {
					nb += 32
				}
				if hb != nb {
					match = false
					break
				}
			}
			if match {
				return true
			}
		}
	}
	return false
}

// lastIndexCaseInsensitive searches backward for needle in haystack without heap allocations.
func lastIndexCaseInsensitive(haystack, needle []byte) int {
	if len(needle) == 0 {
		return len(haystack)
	}
	if len(haystack) < len(needle) {
		return -1
	}
	firstLower := needle[0]
	if firstLower >= 'A' && firstLower <= 'Z' {
		firstLower += 32
	}

	for i := len(haystack) - len(needle); i >= 0; i-- {
		b := haystack[i]
		if b >= 'A' && b <= 'Z' {
			b += 32
		}
		if b == firstLower {
			match := true
			for j := 1; j < len(needle); j++ {
				hb := haystack[i+j]
				if hb >= 'A' && hb <= 'Z' {
					hb += 32
				}
				nb := needle[j]
				if nb >= 'A' && nb <= 'Z' {
					nb += 32
				}
				if hb != nb {
					match = false
					break
				}
			}
			if match {
				return i
			}
		}
	}
	return -1
}

// IsTrapRequest checks whether a request URL path targets the honeypot trap.
func IsTrapRequest(path string) bool {
	return strings.HasPrefix(path, DefaultTrapPrefix)
}
